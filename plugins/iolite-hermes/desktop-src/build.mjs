// Bundle src/ into ../desktop/plugin.js: one ESM file that imports only @hermes/plugin-sdk and
// react. Unminified on purpose, so the shipped file can be read and reviewed. Run from this folder:
//   python3 ../scripts/build_snapshot.py && node build.mjs
import { build } from 'esbuild'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const here = path.dirname(fileURLToPath(import.meta.url))
await build({
  entryPoints: [path.join(here, 'src/plugin.js')],
  outfile: path.join(here, '../desktop/plugin.js'),
  bundle: true,
  format: 'esm',
  platform: 'browser',
  target: 'es2020',
  external: ['@hermes/plugin-sdk', 'react', 'react/jsx-runtime'],
  loader: { '.json': 'json' },
  minify: false,
  legalComments: 'none',
  banner: { js: '/* Iolite desktop half. Generated by desktop-src/build.mjs from desktop-src/src; edit the sources, not this file. */' },
  logLevel: 'info',
})
