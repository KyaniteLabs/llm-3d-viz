/**
 * Parity lock for the Iolite Hermes plugin (plugins/iolite-hermes/decide.py).
 *
 * The plugin is a Python port of src/lib/decide.ts. This test runs the real
 * TypeScript decide logic over a SYNTHETIC seeded catalog (no catalog data, so
 * the fixture is safe to ship in a public plugin) and asserts the committed
 * golden file matches. The plugin's pytest suite asserts the Python port
 * against the same file, so drift on either side fails a suite.
 *
 * Regenerate after an intentional decide.ts change:
 *   IOLITE_GOLDEN_WRITE=1 npx vitest run tests/iolite-plugin-parity.test.ts
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import type { Model } from "../src/data/models";
import {
  catalogSnapshotId,
  catalogSnapshotPayload,
  DEFAULT_INTELLIGENCE_FLOOR,
  shortlistFromDecide,
} from "../src/lib/decide";

const GOLDEN = join(__dirname, "..", "plugins", "iolite-hermes", "tests", "fixtures", "decide-golden.json");

/** Deterministic LCG so the catalog is identical on every run and machine. */
function lcg(seed: number) {
  let s = seed >>> 0;
  return () => {
    s = (Math.imul(s, 1664525) + 1013904223) >>> 0;
    return s / 2 ** 32;
  };
}

function syntheticCatalog(): Model[] {
  const r = lcg(20261110);
  const rows: Model[] = [];
  const pick = (v: number, nullRate = 0.08): number | null => (r() < nullRate ? null : v);
  for (let i = 0; i < 80; i++) {
    const price = pick(Math.round(r() * 30_000) / 1000);
    const tps = pick(Math.round(r() * 400_000) / 1000);
    const intel = pick(Math.round(r() * 1000) / 10);
    rows.push({
      model: `Synthetic Model ${String(i).padStart(2, "0")}`,
      tps,
      blended_price_per_M: price,
      intelligence: intel,
      data_date: "2026-11-10",
    } as unknown as Model);
  }
  // Edge rows: exact ties (name breaks them), rounding boundaries, invalid values.
  const edge = (model: string, tps: number | null, price: number | null, intel: number | null) =>
    rows.push({ model, tps, blended_price_per_M: price, intelligence: intel, data_date: "2026-11-10" } as unknown as Model);
  edge("tie beta", 120, 1.5, 80);
  edge("tie alpha", 120, 1.5, 80);
  edge("Tie Alpha", 120, 1.5, 80);
  edge("round half price", 99.95, 0.125, 70);
  edge("round half price twin", 99.95, 0.1249999, 70);
  edge("free and slow", 1, 0, 60);
  edge("negative price", 50, -1, 90);
  edge("negative tps", -5, 1, 90);
  edge("index over floor exact", 200, 2, 50);
  edge("huge price", 300, 1e6, 95);
  edge("tiny price", 10, 1e-7, 55);
  // Full-precision dominance: the cheapest model must survive a slightly faster, dearer one.
  edge("cheapest slow", 1, 0.001, 65);
  edge("dearer a bit faster", 2, 0.0049, 65);
  edge("close price slow", 10, 0.096, 66);
  edge("close price fast", 20, 0.104, 66);
  return rows;
}

const FLOORS = [0, 30, DEFAULT_INTELLIGENCE_FLOOR, 75, 150, -10];
const BIASES = [-1, -0.5, 0, 0.3, 1, 5];
const NS = [1, 3, 10, 0];

/** The same rows in three speed situations, so both ranking modes are locked. */
function catalogs() {
  const mixed = syntheticCatalog();
  // Every row that survives has a measured, non-negative speed: full cost x speed front.
  const speed = mixed.filter((m) => m.tps !== null && m.tps >= 0);
  // No speed anywhere: the cost x intelligence front.
  const nospeed = mixed.map((m) => ({ ...m, tps: null }) as unknown as Model);
  return { mixed, speed, nospeed };
}

async function buildGolden() {
  const sets = catalogs();
  const cases = [];
  for (const [catalog, models] of Object.entries(sets))
    for (const floor of FLOORS)
      for (const bias of BIASES)
        for (const n of NS) {
          const { eligible, pareto, shortlist, mode } = shortlistFromDecide(models, floor, bias, n);
          cases.push({
            catalog,
            mode,
            floor,
            bias,
            n,
            eligible_ids: eligible.map((m) => m.model),
            pareto_ids: pareto.map((m) => m.model),
            shortlist_ids: shortlist.map((m) => m.model),
          });
        }
  return {
    note: "Generated by tests/iolite-plugin-parity.test.ts from src/lib/decide.ts. Synthetic data only.",
    default_floor: DEFAULT_INTELLIGENCE_FLOOR,
    catalogs: sets,
    snapshot_payload: catalogSnapshotPayload(sets.mixed),
    snapshot_id: await catalogSnapshotId(sets.mixed),
    cases,
  };
}

describe("iolite plugin decide parity golden", () => {
  it("committed golden matches src/lib/decide.ts", async () => {
    const golden = await buildGolden();
    const text = JSON.stringify(golden, null, 1) + "\n";
    if (process.env.IOLITE_GOLDEN_WRITE === "1") writeFileSync(GOLDEN, text);
    expect(readFileSync(GOLDEN, "utf8")).toBe(text);
    // The fixture must exercise every branch it claims to.
    expect(golden.cases.some((c) => c.shortlist_ids.length === 0)).toBe(true);
    expect(golden.cases.some((c) => c.shortlist_ids.length >= 3)).toBe(true);
    expect(new Set(golden.cases.map((c) => c.mode))).toEqual(new Set(["cost_speed", "cost"]));
  });
});
